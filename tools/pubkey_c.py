#!/usr/bin/env python3
"""Emit the nRF5 SDK dfu_public_key.c for a P-256 PEM private key (x and y little-endian, as nrfutil does)."""
import sys

from ecdsa import SigningKey

sk = SigningKey.from_pem(open(sys.argv[1]).read())
raw = sk.get_verifying_key().to_string()  # x||y, big-endian
le = raw[31::-1] + raw[63:31:-1]
rows = ",\n    ".join(", ".join(f"0x{b:02x}" for b in le[i:i + 16]) for i in range(0, 64, 16))
print(f"""/* Generated by tools/pubkey_c.py from keys/private.pem */

#include "stdint.h"
#include "compiler_abstraction.h"

/** @brief Public key used to verify DFU images */
__ALIGN(4) const uint8_t pk[64] =
{{
    {rows}
}};""")
